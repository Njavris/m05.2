#!/usr/bin/env python3
"""Collect the per-function Ghidra decompilation into one readable file.

Outputs:
  reference/decompiled_all.c    all C function bodies, sorted by address
  reference/decompiled_all.asm  all instruction listings, sorted by address

The combined files are reading artifacts, not compilable translation units.
Ghidra types such as undefined2 and labels such as DAT_00c020 are not defined.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.normpath(os.path.join(HERE, "..", "reference"))
MANIFEST = os.path.join(REF, "function_map.csv")

def header(kind):
    if kind == "c":
        return """\
/*
 * Combined Ghidra decompilation - Delphi MT05.2 (Infineon XC164CS-32)
 *
 * Generated by tools/collect_ghidra.py from the per-function files in
 * this directory. The functions are sorted by physical address.
 *
 * This is a READING ARTIFACT, not a compilable translation unit:
 *   - undefined2/undefined4/uint3 and similar types are Ghidra types
 *   - DAT_00xxxx labels are raw memory references, not declarations
 *   - some functions contain decompiler warnings or halt_baddata()
 *
 * Semantic names and the evidence for them are documented in
 * ../SEMANTIC_NAMES.md. Recovered structures are in ../include/firmware_types.h.
 * Use the per-function .c and .asm files for focused work, and the
 * byte-exact listing in ../asm/firmware.s for rebuilding the image.
 */
"""
    return """; Combined Ghidra disassembly - Delphi MT05.2 (Infineon XC164CS-32)
;
; Generated by tools/collect_ghidra.py from the per-function .asm files.
; Sorted by physical address. This is a reading artifact.
"""

def load_rows():
    if not os.path.exists(MANIFEST):
        print(f"missing {MANIFEST}", file=sys.stderr)
        return []
    rows = list(csv.DictReader(open(MANIFEST, newline="")))
    rows.sort(key=lambda r: int(r["entry"], 16))
    return rows

def collect(rows, kind):
    """kind is 'c' or 'asm'."""
    sections = []
    index = []
    missing = 0
    for row in rows:
        key = "c_file" if kind == "c" else "asm_file"
        path = os.path.join(REF, os.path.basename(row[key]))
        if not os.path.exists(path):
            missing += 1
            continue
        text = open(path, "r", encoding="utf-8", errors="replace").read().rstrip()
        index.append((row["entry"], row["name"], os.path.basename(path)))
        if kind == "c":
            sections.append(
                "/* " + "=" * 74 + "\n"
                f" * 0x{int(row['entry'], 16):06X}  {row['name']}\n"
                f" * file: {os.path.basename(path)}\n"
                " * " + "=" * 74 + " */\n"
                + text + "\n\n"
            )
        else:
            sections.append(
                "; " + "=" * 74 + "\n"
                f"; 0x{int(row['entry'], 16):06X}  {row['name']}\n"
                f"; file: {os.path.basename(path)}\n"
                "; " + "=" * 74 + "\n"
                + text + "\n\n"
            )

    if kind == "c":
        toc = ["/*\n * Function index:\n"]
        for entry, name, _ in index:
            toc.append(f" *   0x{int(entry, 16):06X}  {name}\n")
        toc.append(" */\n\n")
    else:
        toc = ["; Function index:\n"]
        for entry, name, _ in index:
            toc.append(f";   0x{int(entry, 16):06X}  {name}\n")
        toc.append("\n")

    out = header(kind) + "".join(toc) + "".join(sections)
    out_path = os.path.join(REF, f"decompiled_all.{kind}")
    open(out_path, "w", encoding="utf-8").write(out)
    print(f"wrote {out_path}: {len(index)} functions, {len(out)} bytes"
          + (f", {missing} missing" if missing else ""))
    return out_path

def main():
    rows = load_rows()
    if not rows:
        return 1
    collect(rows, "c")
    collect(rows, "asm")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
